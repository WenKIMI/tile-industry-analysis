HEADER = ["日期", "指标", "值", "单位", "来源", "链接", "备注"]


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    # utf-8-sig：带 BOM，Excel 双击打开中文不乱码
    try:
        with OUT.open("w", newline="", encoding="utf-8-sig") as f:
            w = csv.writer(f)
            w.writerow(HEADER)
            w.writerows(ROWS)
    except PermissionError:
        tmp = OUT.with_suffix(".new.csv")
        with tmp.open("w", newline="", encoding="utf-8-sig") as f:
            w = csv.writer(f)
            w.writerow(HEADER)
            w.writerows(ROWS)
        raise SystemExit(
            f"raw.csv 正被 Excel/WPS 打开，写不进去。\n"
            f"已生成到 {tmp.name} —— 关掉 Excel 后重跑本脚本，或直接把 new 文件改名为 raw.csv。"
        )

    print(f"已写入 {OUT}")
    print(f"共 {len(ROWS)} 行，覆盖 {len({r[1] for r in ROWS})} 个指标")
    for ind in sorted({r[1] for r in ROWS}):
        pts = [r for r in ROWS if r[1] == ind]
        print(f"  {ind:<14} {len(pts)} 期  {pts[0][0]} ~ {pts[-1][0]}")


if __name__ == "__main__":
    main()
